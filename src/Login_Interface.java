    private void login_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_login_btnActionPerformed
        String user_name=userName_tf.getText();
        String password=password_pf.getText();
        
        Connection con=null;
                try{
                    Class.forName("com.mysql.cj.jdbc.Driver");
                }
                catch(ClassNotFoundException e){
                    System.out.println("Class Not supoorted");          
                }
                try{
                    con=DriverManager.getConnection("jdbc:mysql://localhost:3308/traffic_fine","root","");
                }
                catch(Exception e){
                    System.out.println("Connection Error");
                }
                try{
                    PreparedStatement pst = con.prepareStatement("SELECT * FROM register_details WHERE UserName = ? AND Password = ?");
                    pst.setString(1, user_name);
                    pst.setString(2, password);
                    ResultSet rs = pst.executeQuery();

                    if (rs.next()) {
                        JOptionPane.showMessageDialog(this, "Login Successful!");
                        
                        PanaltyInterface pnlty=new PanaltyInterface();
                        pnlty.setVisible(true);
                        this.hide();

                    } else {
                        JOptionPane.showMessageDialog(this, "Invalid username or password.");
                    }
                }catch(Exception e){
                        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
                
            }
    }//GEN-LAST:event_login_btnActionPerformed

