    private void insert_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_insert_btnActionPerformed
        
        if(nic_tf.getText().isEmpty() || address_tf.getText().isEmpty() || name_tf.getText().isEmpty() ||
            vehicleno_tf.getText().isEmpty() || place_tf.getText().isEmpty() || date_tf.getText().isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Fill the all details");
        }

        else{
        Connection con=null;
            try{
            Class.forName("com.mysql.cj.jdbc.Driver");
            }
            catch(ClassNotFoundException e){
                System.out.println("Class Not supoorted");
            
            }
            try{
            con=DriverManager.getConnection("jdbc:mysql://localhost:3308/traffic_fine","root","");
            }
            catch(Exception e){
                System.out.println("Connection Error");
            }
        try {
            PreparedStatement pstmt=con.prepareStatement("Insert into offence_details(Full_Name,Address,NIC,Vehicle_No,Place,Date,Nature_of_offence,Amount_of_Fine) values (?,?,?,?,?,?,?,?)");
            
            pstmt.setString(1, name_tf.getText());
            pstmt.setString(2, address_tf.getText());
            pstmt.setString(3, nic_tf.getText());
            pstmt.setString(4, vehicleno_tf.getText());
            pstmt.setString(5, place_tf.getText());
            pstmt.setString(6, date_tf.getText());
            pstmt.setString(7, (String)list_cb.getSelectedItem());
            pstmt.setInt(8, Integer.valueOf(amount_tf.getText()));
            
            pstmt.executeUpdate();
            
            Statement stmt=con.createStatement();
            ResultSet rs=stmt.executeQuery("select * from offence_details");
            
            while(rs.next()){
                String fine_id=String.valueOf(rs.getInt("Fine Id"));
                String Name=rs.getString("Full_Name");
                String Address=rs.getString("Address");
                String Nic=rs.getString("NIC");
                String VN=rs.getString("Vehicle_No");
                String pls=rs.getString("Place");
                String dt=rs.getString("Date");
                String lst=rs.getString("Nature_of_offence");
                String amnt=String.valueOf(rs.getInt("Amount_of_Fine"));
                
                String ary[]={fine_id,Name,Address,Nic,VN,pls,dt,lst,amnt};
                DefaultTableModel tblmodel=(DefaultTableModel)gridView.getModel();
                tblmodel.addRow(ary);
                
                refresh();
            }
            
        } catch (SQLException ex) {
            System.out.println(ex);
        }
        }

    }//GEN-LAST:event_insert_btnActionPerformed

