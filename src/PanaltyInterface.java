    public void refresh(){
        Connection con=null;
            try{
            Class.forName("com.mysql.cj.jdbc.Driver");
            }
            catch(ClassNotFoundException e){
                System.out.println("Class Not supoorted");
            
            }
            try{
            con=DriverManager.getConnection("jdbc:mysql://localhost:3308/traffic_fine","root","");
            }
            catch(Exception e){
                System.out.println("Connection Error");
            }
            try{
                PreparedStatement pstmt=con.prepareStatement("select * from offence_details");
                ResultSet rs=pstmt.executeQuery();
                gridView.setModel(DbUtils.resultSetToTableModel(rs));
                
            }catch(Exception ex){System.out.println(ex);}
    }
    
