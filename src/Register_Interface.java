    private void Register_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Register_btnActionPerformed
        String userName=UserName_tf.getText();
        String password=password_pf.getText();
        String confirmPassword=ConfirmPassword_pf.getText();
        
        if(userName.isEmpty() || password.isEmpty() || confirmPassword.isEmpty()){
            JOptionPane.showMessageDialog(rootPane, "Can't Empty the Username or Password");
        }
        else{
            if(!password.equals(confirmPassword)){
                JOptionPane.showMessageDialog(this, "Password does not match.");
            }
            else{
                Connection con=null;
                try{
                    Class.forName("com.mysql.cj.jdbc.Driver");
                }
                catch(ClassNotFoundException e){
                    System.out.println("Class Not supoorted");
            
                }
                try{
                    con=DriverManager.getConnection("jdbc:mysql://localhost:3308/traffic_fine","root","");
                }
                catch(Exception e){
                    System.out.println("Connection Error");
                }
                
                try{
                    PreparedStatement pstmt=con.prepareStatement("INSERT INTO register_details (UserName, Password) VALUES (?, ?)");
                    
                    pstmt.setString(1, userName);
                    pstmt.setString(2, password);
                    pstmt.executeUpdate();
                    
                    JOptionPane.showMessageDialog(this, "Registration Successful!");
                    dispose();
                    new Login_Interface().setVisible(true);
                }catch (SQLIntegrityConstraintViolationException e) {
                    JOptionPane.showMessageDialog(this, "Username already exists.");
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
                }
            }
        }
    }//GEN-LAST:event_Register_btnActionPerformed

